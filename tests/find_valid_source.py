from __future__ import annotations

import ast
import sys
from pathlib import Path
from typing import Any

sys.path.append(str(Path(__file__).parent.parent.parent / "pysource-minimize" / "src"))

from pysource_codegen._codegen import generate_ast
from pysource_codegen._codegen import is_valid_ast
from pysource_codegen._codegen import unparse
from pysource_codegen._codegen_rules import StdGenerator
from pysource_codegen._generator import Invalid
from pysource_minimize import minimize

from ._validation import is_valid_python


def source_bug_found(code: str) -> bool:
    try:
        tree: ast.Module = ast.parse(code)
    except Exception:
        return False

    if not is_valid_python(tree):
        return False

    return not is_valid_ast(tree)


def probe_valid_source(seed: int) -> str | None:
    """
    try to find source code which is valid but can not be generated by codegen()

    The use() hook controls if a specific restriction in the code generation should be applied

    """

    ignore_index: int = 0
    ignored_something: bool = True

    while ignored_something:
        ignored_something = False

        current_index: int = 0

        class TestGenerator(StdGenerator):
            def use(self: Any, condition: bool = True) -> bool:
                nonlocal current_index
                nonlocal ignored_something

                if not condition:
                    return False
                ignore = current_index == ignore_index
                current_index += 1
                if ignore:
                    ignored_something = True
                return not ignore

        try:
            tree = generate_ast(
                seed, node_limit=200, depth_limit=5, generator_type=TestGenerator
            )
        except Invalid:
            # Skipping a rule can make the remaining capture budget impossible.
            # Keep exploring, but surface failures in unmodified generation.
            if not ignored_something:
                raise
            continue
        finally:
            ignore_index += 1

        try:
            code = unparse(tree)
        except Exception as e:
            # print(repr(e))
            continue

        if source_bug_found(code):
            return code

    return None


def minimize_valid_source(seed: int, code: str) -> str:
    code = minimize(code, source_bug_found)
    print()
    print("minimized:")
    print(code)
    return code


def minimize_if_valid(code: str) -> str | None:
    if source_bug_found(code):
        return minimize_valid_source(0, code)
    return None


